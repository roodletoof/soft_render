bool export_to_png(image_t *this, const char *filename) {
    Image raylib_image = GenImageColor(this->width, this->height, BLACK);
    for ( int i = 0; i < this->width * this->height; i++ ) {
        color_t color = this->pixels[i];
        ImageDrawPixel(&raylib_image, i % this->width, i / this->width, palette[color]);
    }
    // Save the image to a file
    bool rc = ExportImage(raylib_image, filename);
    UnloadImage(raylib_image);
    return rc;
}
