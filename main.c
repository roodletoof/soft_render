#include <raylib.h>

#include "image.h"

const color_t pico_colors[] = {
    PICO_0, PICO_1, PICO_2, PICO_3, PICO_4, PICO_5,
    PICO_6, PICO_7, PICO_8, PICO_9, PICO_10, PICO_11,
    PICO_12, PICO_13, PICO_14, PICO_15
};


bool export_to_png(image_t *this, const char *filename);

int main( int arg_count, char *args[] ) {
    image_t *image = &IMAGE_VALUE(128, 128);

    for (int i = 0; i < image->width * image->height; i++) {
        image->pixels[i] = PICO_0;
    }

    // draw a circle for each of the pico colors from color 1 to color 15
    for ( int i = 1; i < 16; i++ ) {
        int x = (i % 4) * 32 + 16;
        int y = (i / 4) * 32 + 16;
        image_draw_circle_filled(image, x, y, 12, pico_colors[i]);
    }

    image_save_path(image, "output.image_t");
    image = image_load_path("output.image_t");

    bool ok = export_to_png(image, "output.png");
    free(image);

    if (!ok) {
        fprintf(stderr, "Failed to export image to PNG\n");
        return 1;
    }
    return 0;
}

